class ModelTransportError(RuntimeError):
    pass


@dataclass(frozen=True)
class ModelResult:
    text: str
    metadata: dict[str, object]


def _codex_home() -> Path:
    configured = os.getenv("CODEX_HOME")
    return Path(configured) if configured else Path.home() / ".codex"


def _configured_mcp_server_names() -> list[str]:
    config_path = _codex_home() / "config.toml"
    try:
        with config_path.open("rb") as handle:
            data = tomllib.load(handle)
    except (FileNotFoundError, OSError, tomllib.TOMLDecodeError):
        return []
    servers = data.get("mcp_servers")
    if not isinstance(servers, dict):
        return []
    return sorted(str(name) for name in servers if str(name).strip())


def _toml_string(value: str) -> str:
    # JSON string escaping is valid for TOML basic strings for the names we emit.
    return json.dumps(value, ensure_ascii=False)


def _transport_config_text() -> str:
    lines = [
        "# JingYou runtime ACP transport-only configuration. Generated by the application.",
        "# ACP is model transport only; do not add project tools or repository context here.",
        'approval_policy = "never"',
        'sandbox_mode = "read-only"',
        'web_search = "disabled"',
        'instructions = ""',
        'developer_instructions = ""',
        "project_doc_max_bytes = 0",
        "project_doc_fallback_filenames = []",
        "project_root_markers = []",
        "",
        "[tools]",
        "web_search = false",
        "view_image = false",
        "",
        "[features]",
    ]
    lines.extend(f"{feature} = false" for feature in _DISABLED_FEATURES)
    lines.extend(
        [
            "skip_host_skill_discovery = true",
            "",
            "[memories]",
            "generate_memories = false",
            "use_memories = false",
        ]
    )
    for name in _configured_mcp_server_names():
        lines.extend(["", f"[mcp_servers.{_toml_string(name)}]", "enabled = false"])
    return "\n".join(lines) + "\n"


def _transport_workspace() -> Path:
    base = Path(os.getenv("LOCALAPPDATA") or tempfile.gettempdir())
    directory = base / "JingYouHealthSystem" / "acp-transport"
    config_dir = directory / ".codex"
    config_dir.mkdir(parents=True, exist_ok=True)

    # This directory is application-owned and deliberately contains no repo/project instruction files.
    for name in ("AGENTS.md", "CLAUDE.md", "PROJECT_RULES.md", "DEEP_CONTEXT_HANDOFF.md"):
        try:
            (directory / name).unlink()
        except FileNotFoundError:
            pass

    config_path = config_dir / "config.toml"
    config = _transport_config_text()
    try:
        current = config_path.read_text(encoding="utf-8")
    except FileNotFoundError:
        current = ""
    if current != config:
        config_path.write_text(config, encoding="utf-8")
    return directory


def generate_text(
    *,
    prompt: str,
    model: str,
    reasoning: str,
    timeout_seconds: int = 240,
) -> ModelResult:
    """Run one pure model turn through the current ACP transport adapter."""

    transport_cwd = _transport_workspace()
    guarded_prompt = f"{_TRANSPORT_GUARD}\n\n{prompt}"
    command = [
        "pwsh",
        "-NoProfile",
        "-ExecutionPolicy",
        "Bypass",
        "-File",
        str(ACP_RUNNER),
        "-Cwd",
        str(transport_cwd),
        "-Model",
        model,
        "-Reasoning",
        reasoning,
        "-TimeoutMinutes",
        str(max(1, (timeout_seconds + 59) // 60)),
    ]
    try:
        completed = subprocess.run(
            command,
            cwd=transport_cwd,
            input=guarded_prompt.encode("utf-8"),
            capture_output=True,
            timeout=timeout_seconds + 30,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise ModelTransportError(f"ACP model transport failed to execute: {exc}") from exc

    try:
        stdout = completed.stdout.decode("utf-8").lstrip("\ufeff").strip()
    except UnicodeDecodeError as exc:
        raise ModelTransportError("ACP model transport returned non-UTF-8 stdout") from exc
    stderr = completed.stderr.decode("utf-8", errors="replace").strip()
    if completed.returncode != 0:
        detail = (stderr or stdout or "ACP model transport failed")[-1600:]
        raise ModelTransportError(detail)
    try:
        envelope = json.loads(stdout)
    except (TypeError, ValueError, json.JSONDecodeError) as exc:
        raise ModelTransportError("ACP model transport returned a malformed transport envelope") from exc
    if not isinstance(envelope, dict) or not isinstance(envelope.get("text"), str):
        raise ModelTransportError("ACP model transport returned no text result")

    audit = envelope.get("audit") if isinstance(envelope.get("audit"), dict) else {}
    tool_events = audit.get("tool_event_count")
    permission_interactions = audit.get("permission_interaction_count")
    if isinstance(tool_events, int) and tool_events != 0:
        raise ModelTransportError(f"Transport-only invariant violated: {tool_events} tool-capability event(s) observed")
    if isinstance(permission_interactions, int) and permission_interactions != 0:
        raise ModelTransportError(
            f"Transport-only invariant violated: {permission_interactions} permission interaction(s) observed"
        )

    metadata: dict[str, object] = {
        "engine": "agentdock-acp-transport-only",
        "transport": "acp",
        "adapter": "codex-acp",
        "model": model,
        "reasoning": reasoning,
        "transport_only": True,
        "tool_event_count": tool_events if isinstance(tool_events, int) else None,
        "permission_interaction_count": permission_interactions if isinstance(permission_interactions, int) else None,
        "event_types": audit.get("event_types") if isinstance(audit.get("event_types"), list) else [],
    }
    return ModelResult(text=envelope["text"], metadata=metadata)
